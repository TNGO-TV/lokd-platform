import fs from 'node:fs';
import { DatabaseSync } from 'node:sqlite';

// Replay migrations: parsing CREATE statements would retain dropped/replaced objects.
const root = new URL('../', import.meta.url);
const files = fs.readdirSync(new URL('drizzle/', root)).filter(name => name.endsWith('.sql')).sort();
const db = new DatabaseSync(':memory:');
try {
  db.exec('PRAGMA foreign_keys=ON');
  for (const file of files) db.exec(fs.readFileSync(new URL(`drizzle/${file}`, root), 'utf8'));
  const objects = db.prepare("SELECT type,name FROM sqlite_master WHERE type IN ('table','trigger','view','index') AND name NOT LIKE 'sqlite_%' AND sql IS NOT NULL ORDER BY type,name").all();
  const manifest = { migration: files.at(-1), objects };
  const output = '// Generated by scripts/generate-readiness-schema.mjs after canonical migration integration.\n'
    + `export const readinessSchema = ${JSON.stringify(manifest, null, 2)} as const;\n`;
  const target = new URL('app/lib/readiness-schema-generated.ts', root);
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(target, 'utf8') !== output) throw new Error('Readiness schema is stale. Regenerate after canonical migration integration.');
  } else fs.writeFileSync(target, output);
  console.log(JSON.stringify({ migration: manifest.migration, requiredObjects: objects.length, checked: process.argv.includes('--check') }));
} finally { db.close(); }

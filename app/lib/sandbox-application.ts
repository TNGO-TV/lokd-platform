import {sandboxRead} from './sandbox-read';
import {sandboxFundingBoundary} from './sandbox-funding-boundary';
import {sandboxSpecialist} from './sandbox-specialist';
import {sandboxEngagement} from './sandbox-engagement';
import {sandboxTraining} from './sandbox-training';
import {SignupError,writeSignup} from './signup-server';
import {requireSandboxCompletion,type SandboxRuntime} from './sandbox-completion-policy';
import type {SigningActor} from './production-signing';
import {manageProductionEvidence} from './production-evidence';
import {operateSandboxWorkforce} from './sandbox-workforce';
import {prepareProductionEntity} from './production-intake';
import {prepareOfficerReview,decideOfficerReview,suspendOfficerApproval} from './production-officer-review';
import * as readiness from './production-readiness';
import * as rereview from './production-rereview';
import {writePsiraCase} from './psira-server';
import {declareProductionSchedule,readProductionSchedule} from './production-schedule';
import {recordProductionService,readProductionService} from './production-service';
import {prepareProductionOrder,readProductionOrders} from './production-orders';
import {operateProduction,readProductionOperations} from './production-operations';
import {manageProductionDocument,issueProductionEnvelope,signProductionEnvelope} from './production-signing';
import {requestPassportDelivery} from './production-passport-delivery';
import {sandboxScan,sandboxIncident,sandboxReleaseAssignment} from './sandbox-service';
import {writePresence} from './officer-presence';
// All actions use the actual application implementation against the guarded binding.
export async function executeSandboxApplication(runtime:SandboxRuntime,actor:SigningActor,service:string,input:Record<string,unknown>,headers:Headers){
 const {db}=await requireSandboxCompletion(runtime);
 switch(service){
 case 'read':return sandboxRead(runtime,actor,input);
 case 'funding_boundary':return sandboxFundingBoundary(runtime,actor,input);
 case 'specialist':return sandboxSpecialist(runtime,actor,input,headers);
 case 'engagement':return sandboxEngagement(runtime,actor,input);
 case 'training':return sandboxTraining(runtime,actor,input);
 case 'intake':return writeSignup(db,actor,input as never);
 case 'entity':return prepareProductionEntity(db,actor,input);
 case 'psira':return writePsiraCase(db,actor,input as never);
 case 'officer_prepare':return prepareOfficerReview(db,actor,input as never);
 case 'officer_decide':return decideOfficerReview(db,actor,input as never);
 case 'officer_suspend':return suspendOfficerApproval(db,actor,String(input.officerId),String(input.reason));
 case 'rule_prepare':return readiness.prepareReadinessRule(db,actor,input as never);
 case 'assessment_prepare':return readiness.prepareReadinessReview(db,actor,input as never);
 case 'readiness_decide':return readiness.decideReadiness(db,actor,input as never);
 case 'opt_in':return readiness.setReadinessOptIn(db,actor,input as never);
 case 'passport_delivery':return requestPassportDelivery(db,actor,input as never);
 case 'passport_prepare':if(typeof input.deliveryId!=='string'||!input.deliveryId)throw new SignupError('Use the officer-owned private delivery request.');return readiness.prepareReadinessPassport(db,actor,input as never);
 case 'readiness_hold':return readiness.holdReadiness(db,actor,input as never);
 case 'request_information':return rereview.requestOfficerRereview(db,actor,input as never);
 case 'disposition_prepare':return rereview.prepareRereviewDisposition(db,actor,input as never);
 case 'disposition_decide':return rereview.decideRereviewDisposition(db,actor,input as never);
 case 'workforce_suspend':return rereview.suspendOfficerWorkforce(db,actor,input as never);
 case 'evidence':return manageProductionEvidence(db,actor,input);
 case 'partner_responsibility':return operateSandboxWorkforce(runtime,actor,input);
 case 'schedule':return declareProductionSchedule(db,actor,input);
 case 'schedule_read':return readProductionSchedule(db,actor);
 case 'orders':return prepareProductionOrder(db,actor,input);
 case 'orders_read':return readProductionOrders(db,actor);
 case 'service':return recordProductionService(db,actor,input,headers);
 case 'service_read':return readProductionService(db,actor);
 case 'operations':return operateProduction(db,actor,input,headers,true,{});
 case 'operations_read':return readProductionOperations(db,actor);
 case 'document':return manageProductionDocument(db,actor,input);
 case 'envelope':return issueProductionEnvelope(db,actor,input);
 case 'sign':return signProductionEnvelope(db,actor,input);
 case 'assignment_release':return sandboxReleaseAssignment(runtime,actor,input,headers);
 case 'scan':return sandboxScan(runtime,actor,input,headers);
 case 'incident':return sandboxIncident(runtime,actor,input);
 case 'presence':return writePresence(db,actor.userId,null,input);
 default:throw new SignupError('Unsupported sandbox application service.');
 }
}
